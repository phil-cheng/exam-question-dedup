def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "正式题目"
    ws.append(["试题列表"])
    ws.append(["查重实验数据集：原12道 + 特征追加题（A/C/D/E/F/G/H/I 组）"])
    ws.append(HEADER)
    for code, qtype, stem, opts, answer in Q:
        row = [code, "未分类", qtype, "计算机", "基础知识", "编程知识", 0.5, "中等", 30.0, stem]
        for i in range(6):
            row.append(opts[i] if i < len(opts) else "")
        row.append(answer)
        ws.append(row)

    out = Path(__file__).resolve().parent / "test_dataset.xlsx"
    wb.save(out)
    print(f"写入 {out}，共 {len(Q)} 道题")


if __name__ == "__main__":
    main()
