def _fill_to_base(existing: list[tuple], target_unique: int) -> list[tuple]:
    """笛卡尔积生成互不相同的填充题，禁止再套模重复同一题面。"""
    rows = list(existing)
    used_codes = {r[0] for r in rows}
    used_stems = {r[4] for r in rows}
    seq = 930
    entities = [
        "进程", "线程", "协程", "页表", "TLB", "inode", "套接字", "文件描述符",
        "信号量", "管程", "自旋锁", "死锁检测", "工作集", "缺页异常", "DMA",
        "流水线", "分支预测", "Cache行", "写缓冲", "中断向量", "系统调用",
        "B+树", "WAL", "检查点", "间隙锁", "物化视图", "查询计划", "代价估计",
        "拥塞窗口", "滑动窗口", "ARP缓存", "NAT表项", "AS号", "TTL",
        "数字证书", "盐值", "签名验签", "权限提升", "沙箱", "审计日志",
        "符号表", "抽象语法树", "寄存器分配", "活跃变量", "基本块",
        "启发式函数", "损失函数", "学习率", "过拟合", "特征交叉",
    ]
    aspects = [
        "时间开销", "空间占用", "正确性条件", "失败时的回退", "并发安全性",
        "可扩展性", "可观测性", "与相邻模块的接口", "最坏情况行为", "工程上的常见误用",
    ]
    claims = [
        "必须先满足前置不变量再进入临界区",
        "应避免在持锁路径上做阻塞式I/O",
        "缓存命中率下降时延迟会非线性变差",
        "错误路径也要保证资源被释放",
        "跨节点复制会引入可见性延迟",
        "局部性差会让层次存储的收益接近于零",
        "缺少背压时上游会把下游打满",
        "用经验阈值代替形式证明时要留下可回滚开关",
        "热路径上的额外日志可能改变时序",
        "默认可变共享状态是数据竞争的温床",
    ]

    def next_code() -> str:
        nonlocal seq
        while True:
            seq += 1
            code = f"U{seq:04d}"
            if code not in used_codes:
                used_codes.add(code)
                return code

    i = 0
    while len(rows) < target_unique:
        ent = entities[i % len(entities)]
        asp = aspects[(i // len(entities)) % len(aspects)]
        claim = claims[(i // (len(entities) * len(aspects))) % len(claims)]
        # 再加一层序号，保证笛卡尔用尽后仍不撞题面
        serial = i + 1
        if i % 3 == 0:
            stem = f"评估「{ent}」的{asp}时，更合理的判断是：{claim}。（案例{serial}）"
            qtype, opts, ans = "判断题", [], "A"
            module, kp = "综合压测", ent
        elif i % 3 == 1:
            stem = f"若系统在「{ent}」上暴露出{asp}问题，下列哪项更接近根因分析方向？"
            opts = [claim, "把该组件从内核移到浏览器就能解决",
                    "只增加注释而不改控制流", "关闭所有日志即可恢复吞吐"]
            qtype, ans = "单选题", "A"
            module, kp = "综合压测", f"{ent}-{asp}"
        else:
            stem = f"关于{ent}与{asp}，下列说法正确的有哪些？"
            opts = [claim, f"{ent}可以完全忽略{asp}",
                    "该问题只会出现在单核机器", "升级编译器版本必然消除该问题"]
            qtype, ans = "多选题", "A"
            module, kp = "综合压测", asp
        if stem not in used_stems:
            used_stems.add(stem)
            rows.append((next_code(), qtype, module, kp, stem, opts, ans))
        i += 1
        if i > 20000:
            raise RuntimeError("填充独立题失败，组合耗尽。")
    return rows[:target_unique]


def _make_planted(unique: list[tuple]) -> list[tuple]:
    """从独立题中抽出子集，生成四类近重复。"""
    planted_qs: list[tuple] = []
    # 选前 80 道手写题做埋点，避免填空题过于同构
    bases = unique[:80]

    # 20 对标点/空格
    for i, q in enumerate(bases[:20]):
        code, qtype, module, kp, stem, opts, ans = q
        pcode = f"P{i+1:04d}"
        new_stem = (
            stem.replace("(", "（")
            .replace(")", "）")
            .replace(",", "，")
            .replace(".", "。")
            .replace("?", "？")
        )
        if new_stem == stem:
            new_stem = stem.replace("的", "的 ").replace("是", "是 ")
        planted_qs.append((pcode, qtype, module, kp, new_stem, list(opts), ans))
        _plant(code, pcode, "punct")

    # 20 对选项对调（判断题没有选项则改成轻微措辞）
    for i, q in enumerate(bases[20:40]):
        code, qtype, module, kp, stem, opts, ans = q
        pcode = f"P{i+21:04d}"
        new_opts = list(opts)
        if len(new_opts) >= 2:
            new_opts[0], new_opts[1] = new_opts[1], new_opts[0]
            # 选项对调后答案字母跟着换
            trans = {"A": "B", "B": "A"}
            new_ans = "".join(trans.get(ch, ch) for ch in ans)
        else:
            new_stem = stem[:-1] + "（判断）。" if stem.endswith("。") else stem + "（判断）"
            planted_qs.append((pcode, qtype, module, kp, new_stem, new_opts, ans))
            _plant(code, pcode, "punct")
            continue
        planted_qs.append((pcode, qtype, module, kp, stem, new_opts, new_ans))
        _plant(code, pcode, "option")

    # 20 对换说法
    paraphrases = {
        "U0005": "Python 的 list 本质上可看作可自动扩容的动态数组。",
        "U0006": "与数组相比，链表不能高效地按下标随机访问。",
        "U0007": "平均情况下能达到 O(n log n) 的排序算法是哪一种？",
        "U0008": "在已经排好序的数组里找某个元素，更合适的方法是？",
        "U0011": "TCP 建立连接需要交换几个握手报文？",
        "U0013": "后放入栈的元素会先被取出。",
        "U0014": "两个不同的关键字经过哈希函数计算后得到了相同的地址，这种现象被称为什么？",
        "U0015": "操作系统里，资源按进程分配，CPU 时间片按线程调度。",
        "U0020": "分组之后还想按聚合结果再过滤，应该用哪个 SQL 子句？",
        "U0022": "一个事务里的操作不允许只做一半，这描述的是原子性。",
        "U0024": "Cache 存在的核心原因是 CPU 太快、主存相对太慢。",
        "U0026": "浏览器访问网页所用的 HTTP，位于网络体系结构的哪一层？",
        "U0033": "RSA 使用一对公钥和私钥，属于？",
        "U0036": "实现 BFS 时，通常用哪种数据结构保存待访问节点？",
        "U0038": "若算法耗时不随输入规模变化，其时间复杂度记为 O(1)。",
        "U0046": "比较下列排序，哪一种能保证相等元素相对次序不变？",
        "U0050": "要想使用二分查找，输入序列必须满足什么前提？",
        "U0054": "LIFO 对应的经典数据结构是？",
        "U0066": "为什么很多数据库的二级索引/聚簇叶子更愿意用 B+ 树？",
        "U0073": "TCP 慢启动时 cwnd 大致如何变化？",
    }
    used = 0
    for q in bases:
        code = q[0]
        if code not in paraphrases:
            continue
        pcode = f"P{41+used:04d}"
        code, qtype, module, kp, stem, opts, ans = q
        planted_qs.append((pcode, qtype, module, kp, paraphrases[code], list(opts), ans))
        _plant(code, pcode, "paraphrase")
        used += 1
        if used >= 20:
            break

    # 20 对只差数字/关键字（应被查到或落入灰区，取决于模型）
    number_src = [q for q in unique if any(ch.isdigit() for ch in q[4])][:20]
    for i, q in enumerate(number_src):
        code, qtype, module, kp, stem, opts, ans = q
        pcode = f"P{61+i:04d}"
        new_stem = stem
        for a, b in [("3", "4"), ("2", "3"), ("80", "8080"), ("443", "80"),
                     ("1", "2"), ("n-1", "n+1")]:
            if a in new_stem:
                new_stem = new_stem.replace(a, b, 1)
                break
        if new_stem == stem:
            new_stem = stem + "（版本2）"
        planted_qs.append((pcode, qtype, module, kp, new_stem, list(opts), ans))
        _plant(code, pcode, "number")

    return planted_qs


def build() -> tuple[list[tuple], list[tuple[str, str, str]]]:
    PLANTED.clear()
    unique: list[tuple] = []
    unique.extend(_bank_unique())
    unique.extend(_bank_long())
    unique.extend(_expand_family())
    unique.extend(_noise())
    unique = _fill_to_base(unique, 920)
    planted = _make_planted(unique)
    all_qs = unique + planted
    # 超量则裁到 1000，但必须保住埋点题
    if len(all_qs) > 1000:
        keep_codes = {a for a, _, _ in PLANTED} | {b for _, b, _ in PLANTED}
        kept_planted = [q for q in all_qs if q[0] in keep_codes or q[0].startswith("P")]
        kept_unique = [q for q in unique if q[0] in keep_codes]
        others = [q for q in unique if q[0] not in keep_codes]
        need = 1000 - len(kept_planted) - len(kept_unique)
        all_qs = kept_unique + others[:need] + kept_planted
    elif len(all_qs) < 1000:
        raise RuntimeError(f"只生成了 {len(all_qs)} 道，不足 1000。")
    return all_qs[:1000], list(PLANTED)


def main() -> None:
    qs, planted = build()
    out_dir = Path(__file__).resolve().parent
    xlsx = out_dir / "stress_1000.xlsx"
    meta = out_dir / "stress_1000_meta.json"

    wb = Workbook()
    ws = wb.active
    ws.title = "正式题目"
    ws.append(["试题列表"])
    ws.append(["压测数据集：1000 道，含埋点近重复"])
    ws.append(HEADER)
    for code, qtype, module, kp, stem, opts, answer in qs:
        row = [code, "压测卷", qtype, module, "计算机相关", kp, 1, "中等", 30, stem]
        for i in range(6):
            row.append(opts[i] if i < len(opts) else "")
        row.append(answer)
        ws.append(row)
    wb.save(xlsx)

    meta.write_text(
        json.dumps(
            {
                "n": len(qs),
                "planted": [{"a": a, "b": b, "kind": k} for a, b, k in planted],
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"写入 {xlsx}，共 {len(qs)} 道；埋点对 {len(planted)}")


if __name__ == "__main__":
    main()
